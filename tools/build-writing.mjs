#!/usr/bin/env node
/* ============================================================
   Build the writing archive.

   Source of truth:  content/writing/posts.json         (metadata, newest first)
                     content/writing/<slug>.md          (markdown, written in the studio)
                     content/writing/<slug>.html        (legacy imported posts)
                     assets/writing/<slug>/             (images)

   Output (committed, served by GitHub Pages):
                     writing/<slug>/index.html
                     writing/posts.js                   (list for the homepage)

   Drafts (draft: true in posts.json) are skipped entirely, so an
   unfinished post never leaks onto the live site.

   Run after adding or editing a post:

     node tools/build-writing.mjs
   ============================================================ */

import { readFile, writeFile, mkdir, access } from "node:fs/promises";
import path from "node:path";

import { page, SITE } from "./post-page.mjs";
import { renderMarkdown, readingMinutes, wrapTables } from "./md.mjs";

const ROOT = path.resolve(import.meta.dirname, "..");
const CONTENT = path.join(ROOT, "content/writing");

const exists = async (p) =>
  access(p).then(
    () => true,
    () => false
  );

const posts = JSON.parse(await readFile(path.join(CONTENT, "posts.json"), "utf8"));

const published = posts.filter((p) => !p.draft);
const drafts = posts.filter((p) => p.draft);

/* --- render each post -------------------------------------- */

let built = 0;
const list = [];

for (let i = 0; i < published.length; i++) {
  const post = published[i];
  if (!/^[a-z0-9][a-z0-9-]*$/.test(post.slug)) {
    throw new Error(`bad slug "${post.slug}" — use lowercase letters, digits and dashes`);
  }

  let body;
  let words = post.words;
  let hasMath = false;

  const mdPath = path.join(CONTENT, `${post.slug}.md`);
  const htmlPath = path.join(CONTENT, `${post.slug}.html`);

  if (await exists(mdPath)) {
    const md = await readFile(mdPath, "utf8");
    const out = renderMarkdown(md, { slug: post.slug });
    body = out.html;
    hasMath = out.hasMath;
    words = words || out.words;
  } else if (await exists(htmlPath)) {
    body = wrapTables(
      (await readFile(htmlPath, "utf8"))
        /* provenance comments are for the repo, not the page */
        .replace(/^<!--[\s\S]*?-->\n/, "")
    );
  } else {
    throw new Error(`no body for "${post.slug}" — expected ${post.slug}.md or ${post.slug}.html`);
  }

  const minutes = post.minutes || readingMinutes(words || 0);

  const outDir = path.join(ROOT, "writing", post.slug);
  await mkdir(outDir, { recursive: true });
  await writeFile(
    path.join(outDir, "index.html"),
    page({ ...post, minutes }, body.trim(), published[i - 1], published[i + 1], { hasMath })
  );
  built++;

  list.push({
    title: post.title,
    date: post.date,
    iso: post.dateISO,
    url: `/writing/${post.slug}/`,
    tag: post.tag || "engineering",
    minutes,
  });
}

/* --- the homepage reads its list from here ----------------- */

await mkdir(path.join(ROOT, "writing"), { recursive: true });
await writeFile(
  path.join(ROOT, "writing/posts.js"),
  `/* Generated by tools/build-writing.mjs — edit content/writing/posts.json instead. */\n` +
    `window.WRITING_POSTS = ${JSON.stringify(list, null, 2)};\n`
);

/* --- canonical hints for the bearblog originals ------------- */

const canonical = published.filter((p) => p.source);
await writeFile(
  path.join(CONTENT, "bearblog-canonical.md"),
  [
    "# Canonical URLs for the bearblog originals",
    "",
    "For each post on defygrad.bearblog.dev, open it in the dashboard, add the",
    "canonical_url line shown below next to the existing title: / link: headers",
    "(above the --- separator), and save. That tells search engines the GitHub",
    "Pages copy is the original without breaking the old URL.",
    "",
    ...canonical.map((p) => `## ${p.title}\ncanonical_url: ${SITE}/writing/${p.slug}/\n`),
  ].join("\n")
);

/* --- keep the hand-written counts in index.html in step ----- */

const indexPath = path.join(ROOT, "index.html");
let index = await readFile(indexPath, "utf8");
const before = index;
const n = published.length;

index = index
  .replace(/(<dt>Essays<\/dt><dd>)\d+(<\/dd>)/, `$1${n}$2`)
  .replace(/\b\d+( technical writeups\b)/, `${n}$1`)
  .replace(/(placeholder="Search )\d+( posts…")/, `$1${n}$2`)
  .replace(/(Show all )\d+( posts)/, `$1${n}$2`);

if (index !== before) await writeFile(indexPath, index);

/* --- report ------------------------------------------------ */

console.log(`built ${built} post pages + writing/posts.js + bearblog-canonical.md`);
console.log(`  published: ${n}`);
if (drafts.length) {
  console.log(`  drafts skipped: ${drafts.length} (${drafts.map((d) => d.slug).join(", ")})`);
}
console.log(`  index.html counts: ${index === before ? "already in sync" : `updated to ${n}`}`);
